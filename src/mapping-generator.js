const yaml = require("js-yaml");
const { matchComponents } = require("./cross-platform-matcher");

const PLATFORMS = ["ios", "android", "web"];

const HEADER = `# component-mapping.yaml — generated by fractionator --init-mapping
#
# This is a STARTER file. Fractionator has pre-filled its best guesses:
#   - exact and normalized name matches across platforms
#   - single-platform components (the other platforms are left as null)
#
# Curate it: rename concepts, link components that serve the same purpose but
# are named differently (e.g. ios: RowLink / android: NHSRowItem), and fill in
# nulls where a component should exist on another platform.
#
# Then pass it back in:  fractionator --ios ... --android ... --mapping component-mapping.yaml
`;

/**
 * Generate a starter component-mapping.yaml string from detected components.
 *
 * Runs the auto-matcher (no existing mapping) and serializes every resulting
 * concept — matched pairs pre-filled, platform-only entries with the present
 * platform filled and the rest null.
 *
 * @param {Object<string, {name: string}[]>} platformComponents
 * @param {{prefixes?: string[], suffixes?: string[]}} [config]
 * @returns {string} - YAML document text.
 */
function generateMappingYaml(platformComponents, config = {}) {
  const platforms = PLATFORMS.filter((p) =>
    Array.isArray(platformComponents[p]),
  );

  const alignment = matchComponents(platformComponents, null, config);

  const mappings = alignment.map((entry) => {
    const row = { concept: entry.concept };
    for (const p of platforms) {
      row[p] = entry.platforms[p] ?? null;
    }
    return row;
  });

  const body = yaml.dump(
    { mappings },
    { lineWidth: 100, noRefs: true, quotingType: '"' },
  );

  return `${HEADER}\n${body}`;
}

module.exports = { generateMappingYaml };
